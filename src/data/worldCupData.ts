// 获取球队所在小组的比赛
export const getGroupMatches = (groupId: string, teamId: string): Match[] => {
  const otherTeams = groups[groupId]?.filter(t => t !== teamId) || [];
  return otherTeams.map((opponent, index) => ({
    id: `group-${groupId}-${teamId}-${opponent}`,
    stage: 'group' as const,
    teamA: teamId,
    teamB: opponent,
    date: new Date().toISOString(),
    groupMatchNumber: index + 1,
  }));
};

// 根据ID获取球队信息
export const getTeamById = (id: string): Team | undefined => {
  return teams.find(t => t.id === id);
};

// 获取小组所有球队
export const getTeamsInGroup = (groupId: string): Team[] => {
  const teamIds = groups[groupId] || [];
  return teamIds.map(id => getTeamById(id)).filter((team): team is Team => team !== undefined);
};

// 获取所有小组列表
export const getAllGroups = (): string[] => {
  return Object.keys(groups);
};
